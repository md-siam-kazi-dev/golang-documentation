const RELATED_LIMIT = 8;

/** Curated cross-links first, then same-section siblings. */
export const getRelatedDocs = cache((key: string): Doc[] => {
  const docs = getDocs();
  const sectionSlug = key.split("/")[0];
  const seen = new Set<string>([key]);
  const related: Doc[] = [];

  const add = (candidate: string): boolean => {
    if (seen.has(candidate) || related.length >= RELATED_LIMIT) return false;
    const doc = docs.find((d) => d.slug.join("/") === candidate);
    if (!doc) return false;
    seen.add(candidate);
    related.push(doc);
    return true;
  };

  for (const candidate of RELATED[key] ?? []) add(candidate);

  for (const doc of docs) {
    if (related.length >= RELATED_LIMIT) break;
    if (doc.slug[0] !== sectionSlug) continue;
    add(doc.slug.join("/"));
  }

  return related;
});

export type Crumb = { name: string; href: string };

export function getDocBreadcrumbs(doc: Doc): Crumb[] {
  const href = `/docs/${doc.slug.join("/")}`;
  return [
    { name: "Docs", href: "/docs" },
    { name: getShortSection(doc.section), href: `/docs/${doc.slug[0]}` },
    { name: doc.title, href },
  ];
}

export function getSectionBreadcrumbs(sectionSlug: string, sectionTitle: string): Crumb[] {
  return [
    { name: "Docs", href: "/docs" },
    { name: getShortSection(sectionTitle), href: `/docs/${sectionSlug}` },
  ];
}

export function breadcrumbJsonLd(crumbs: Crumb[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map((crumb, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: crumb.name,
      item: absoluteUrl(crumb.href),
    })),
  };
}
