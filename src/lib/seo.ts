const GENERIC_DESCRIPTION = /^Learn about .+ in Go\.$/;

/** Strip inline markdown so derived text reads cleanly in search results. */
function stripInlineMarkdown(text: string): string {
  return text
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/`([^`]*)`/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

function truncate(text: string, limit: number): string {
  if (text.length <= limit) return text;
  const clipped = text.slice(0, limit);
  const lastSpace = clipped.lastIndexOf(" ");
  const cut = lastSpace > limit * 0.6 ? clipped.slice(0, lastSpace) : clipped;
  return `${cut.trimEnd()}…`;
}

/**
 * The page's opening prose, skipping headings, lists, quotes, code and
 * horizontal rules. Normally stops at the first paragraph boundary; when that
 * paragraph is very short, one more is appended so the snippet isn't thin.
 */
function introExcerpt(body: string, limit: number, min = 60): string {
  const parts: string[] = [];
  const buf: string[] = [];
  let inFence = false;

  const flush = (): void => {
    const text = stripInlineMarkdown(buf.join(" "));
    buf.length = 0;
    if (text) parts.push(text.replace(/[:;]+$/, "").trim());
  };

  const joined = (): string => parts.join(" ");
  const complete = (): boolean => joined().length >= min;
  const result = (): string => (joined() ? truncate(joined(), limit) : "");

  for (const raw of body.split(/\r?\n/)) {
    const line = raw.trim();

    if (line.startsWith("```")) {
      flush();
      if (complete()) break;
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;

    if (!line) {
      flush();
      if (complete()) break;
      continue;
    }

    const isStructural =
      /^#{1,6}\s/.test(line) ||
      /^[<>]/.test(line) ||
      /^([-*+]|\d+\.)\s/.test(line) ||
      /^[-=_*]{3,}$/.test(line) ||
      line.startsWith(">") ||
      line.startsWith("|");

    if (isStructural) {
      flush();
      continue;
    }

    // A bare label line (e.g. "Syntax:") is not prose — treat it as noise.
    if (line.length < 40 && line.endsWith(":")) continue;

    buf.push(line);
  }

  flush();
  return result();
}

/**
 * A title suited to search intent without changing the visible H1 or sidebar
 * label. Pages whose title already names Go are left alone.
 */
export function getSeoTitle(doc: Doc): string {
  const key = doc.slug.join("/");
  const override = TITLE_OVERRIDES[key];
  if (override) return override;

  const base = /\bgolang\b|\bgo\b/i.test(doc.title)
    ? doc.title
    : `${doc.title} in Go`;

  // Titles reused across sections (e.g. "Middleware") need disambiguating.
  if (getDuplicateTitles().has(doc.title)) {
    return `${base} — ${getShortSection(doc.section)}`;
  }
  return base;
}

/**
 * Frontmatter descriptions are used when they are genuinely descriptive.
 * Placeholder/truncated ones fall back to the page's own opening paragraph.
 */
export function getSeoDescription(doc: Doc, limit = 155): string {
  // Placeholder bodies must never surface as meta text.
  if (doc.isPlaceholder) {
    return `${doc.title} in Go — part of the ${getShortSection(
      doc.section,
    )} section of ${SITE_NAME}.`;
  }

  const frontmatter = doc.description.trim();
  const usable =
    frontmatter.length >= 50 &&
    !GENERIC_DESCRIPTION.test(frontmatter) &&
    !frontmatter.endsWith(":");

  if (usable) return frontmatter;

  const derived = introExcerpt(doc.body, limit);
  if (derived) return derived;

  return `Learn about ${doc.title.toLowerCase()} in Go, part of the ${getShortSection(
    doc.section,
  )} section of ${SITE_NAME}.`;
}

export function getSeoKeywords(doc: Doc): string[] {
  const short = getShortSection(doc.section);
  const values = [doc.title, `Go ${doc.title}`, short, "Go", "Golang"];
  return [...new Set(values.filter(Boolean))];
}

